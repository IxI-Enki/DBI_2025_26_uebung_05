-- DIM_TIME - IMPROVED VERSION
----------------------------------------------------------------------------------------------------
-- IMPROVEMENT: Added FULL_DATE column for RANGE INTERVAL operations in analytic functions
-- This eliminates the need for runtime TO_DATE conversions and improves query performance
-- 
-- Example use case:
--   AVG(amount) OVER (ORDER BY full_date RANGE BETWEEN INTERVAL '10' DAY PRECEDING AND CURRENT ROW)
----------------------------------------------------------------------------------------------------

CREATE TABLE DIM_TIME (
  ID         NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  YEAR       NUMBER        NOT NULL,
  MONTH      NUMBER        NOT NULL,
  DAY        NUMBER        NOT NULL,
  FULL_DATE  DATE          NOT NULL,  -- NEW: Complete date for analytic functions
  CONSTRAINT UQ_DIM_TIME UNIQUE (YEAR, MONTH, DAY),
  CONSTRAINT UQ_DIM_TIME_DATE UNIQUE (FULL_DATE),
  -- Data validation constraints
  CONSTRAINT CHK_DIM_TIME_YEAR  CHECK (YEAR BETWEEN 1900 AND 2100),
  CONSTRAINT CHK_DIM_TIME_MONTH CHECK (MONTH BETWEEN 1 AND 12),
  CONSTRAINT CHK_DIM_TIME_DAY   CHECK (DAY BETWEEN 1 AND 31)
);

COMMENT ON TABLE DIM_TIME IS 'Time dimension with date components and full date for analytics';
COMMENT ON COLUMN DIM_TIME.ID IS 'Surrogate key (auto-generated)';
COMMENT ON COLUMN DIM_TIME.YEAR IS 'Year component (1900-2100)';
COMMENT ON COLUMN DIM_TIME.MONTH IS 'Month component (1-12)';
COMMENT ON COLUMN DIM_TIME.DAY IS 'Day component (1-31)';
COMMENT ON COLUMN DIM_TIME.FULL_DATE IS 'Complete date - optimal for RANGE INTERVAL in analytic functions';

