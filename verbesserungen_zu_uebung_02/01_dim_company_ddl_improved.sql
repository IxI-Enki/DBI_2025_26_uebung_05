-- DIM_PRODUCT (denormalized with category) - IMPROVED VERSION
----------------------------------------------------------------------------------------------------
-- IMPROVEMENT: Added CHECK constraints for price validation
----------------------------------------------------------------------------------------------------

CREATE TABLE DIM_PRODUCT (
  ID                 NUMBER         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PRODUCT_NAME       VARCHAR2(255)  NOT NULL,
  CATEGORY_NAME      VARCHAR2(255)  NOT NULL,
  STANDARD_COST      NUMBER(9,2),
  LIST_PRICE         NUMBER(9,2),
  SOURCE_PRODUCT_ID  NUMBER         NOT NULL,
  CONSTRAINT UQ_DIM_PRODUCT_SRC UNIQUE (SOURCE_PRODUCT_ID),
  -- Data validation constraints
  CONSTRAINT CHK_DIM_PRODUCT_COST CHECK (STANDARD_COST IS NULL OR STANDARD_COST >= 0),
  CONSTRAINT CHK_DIM_PRODUCT_PRICE CHECK (LIST_PRICE IS NULL OR LIST_PRICE >= 0),
  CONSTRAINT CHK_DIM_PRODUCT_MARGIN CHECK (
    STANDARD_COST IS NULL OR LIST_PRICE IS NULL OR LIST_PRICE >= STANDARD_COST
  )
);

COMMENT ON TABLE DIM_PRODUCT IS 'Product dimension (denormalized with category)';
COMMENT ON COLUMN DIM_PRODUCT.ID IS 'Surrogate key (auto-generated)';
COMMENT ON COLUMN DIM_PRODUCT.PRODUCT_NAME IS 'Product name';
COMMENT ON COLUMN DIM_PRODUCT.CATEGORY_NAME IS 'Product category (denormalized for performance)';
COMMENT ON COLUMN DIM_PRODUCT.STANDARD_COST IS 'Standard cost (must be >= 0)';
COMMENT ON COLUMN DIM_PRODUCT.LIST_PRICE IS 'List price (must be >= standard_cost)';
COMMENT ON COLUMN DIM_PRODUCT.SOURCE_PRODUCT_ID IS 'Original product_id from OLTP system';

